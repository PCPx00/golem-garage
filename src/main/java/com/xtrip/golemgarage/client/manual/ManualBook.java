package com.xtrip.golemgarage.client.manual;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.xtrip.golemgarage.GolemGarage;
import com.xtrip.golemgarage.golem.GolemData;
import com.xtrip.golemgarage.golem.GolemMaterials;
import com.xtrip.golemgarage.item.GolemItem;
import com.xtrip.golemgarage.item.ModDataComponents;
import net.minecraft.client.Minecraft;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.Resource;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;

import java.io.Reader;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * The manual's contents, read from assets/golemgarage/manual/book.json (generated by tools/golemgen/manual.py).
 * Loaded each time the book opens, so resource packs and reloads apply straight away.
 */
public final class ManualBook {
    public static final ResourceLocation SOURCE = ResourceLocation.fromNamespaceAndPath(GolemGarage.MOD_ID, "manual/book.json");

    public final String title;
    public final String subtitle;
    public final String intro;
    public final List<Category> categories = new ArrayList<>();
    public final Map<String, Entry> entries = new LinkedHashMap<>();
    /** Item key (id, or id@material) to the entry about it. */
    public final Map<String, String> index = new HashMap<>();

    public static final class Category {
        public String id;
        public String title;
        public String desc;
        public ItemStack icon;
        public final List<Entry> entries = new ArrayList<>();
    }

    public static final class Entry {
        public String id;
        public String title;
        public ItemStack icon;
        public Category category;
        public final List<JsonObject> pages = new ArrayList<>();
        /** Pages after text overflow is split; built on first view. */
        public List<ManualPage> laidOut;
    }

    private ManualBook(JsonObject root) {
        title = str(root, "title", "Manual");
        subtitle = str(root, "subtitle", "");
        intro = str(root, "intro", "");
        for (JsonElement ce : root.getAsJsonArray("categories")) {
            JsonObject co = ce.getAsJsonObject();
            Category c = new Category();
            c.id = co.get("id").getAsString();
            c.title = str(co, "title", c.id);
            c.desc = str(co, "desc", "");
            c.icon = stack(str(co, "icon", "minecraft:book"));
            for (JsonElement ee : co.getAsJsonArray("entries")) {
                JsonObject eo = ee.getAsJsonObject();
                Entry e = new Entry();
                e.id = eo.get("id").getAsString();
                e.title = str(eo, "title", e.id);
                e.icon = stack(str(eo, "icon", "minecraft:paper"));
                e.category = c;
                for (JsonElement pe : eo.getAsJsonArray("pages")) {
                    e.pages.add(pe.getAsJsonObject());
                }
                c.entries.add(e);
                entries.put(e.id, e);
            }
            categories.add(c);
        }
        if (root.has("index")) {
            for (Map.Entry<String, JsonElement> ie : root.getAsJsonObject("index").entrySet()) {
                index.put(ie.getKey(), ie.getValue().getAsString());
            }
        }
    }

    public static Optional<ManualBook> load() {
        try {
            // A translated book (manual/<language>/book.json) wins; English is the fallback.
            String lang = Minecraft.getInstance().getLanguageManager().getSelected();
            Optional<Resource> res = Minecraft.getInstance().getResourceManager().getResource(
                    ResourceLocation.fromNamespaceAndPath(GolemGarage.MOD_ID, "manual/" + lang + "/book.json"));
            if (res.isEmpty()) {
                res = Minecraft.getInstance().getResourceManager().getResource(SOURCE);
            }
            if (res.isEmpty()) {
                return Optional.empty();
            }
            try (Reader reader = res.get().openAsReader()) {
                return Optional.of(new ManualBook(JsonParser.parseReader(reader).getAsJsonObject()));
            }
        } catch (Exception e) {
            GolemGarage.LOGGER.error("Could not read the Golem Engineer's Manual", e);
            return Optional.empty();
        }
    }

    /** The entry an item should open, if any. */
    public Entry entryFor(ItemStack stack) {
        if (stack.isEmpty()) {
            return null;
        }
        String id = BuiltInRegistries.ITEM.getKey(stack.getItem()).toString();
        String mat = stack.get(ModDataComponents.MATERIAL.get());
        String key = mat != null ? index.get(id + "@" + mat) : null;
        if (key == null) {
            key = index.get(id);
        }
        return key == null ? null : entries.get(key);
    }

    static String str(JsonObject o, String key, String def) {
        return o.has(key) ? o.get(key).getAsString() : def;
    }

    static List<String> strings(JsonObject o, String key) {
        List<String> out = new ArrayList<>();
        if (o.has(key)) {
            JsonArray a = o.getAsJsonArray(key);
            for (JsonElement e : a) {
                out.add(e.getAsString());
            }
        }
        return out;
    }

    /**
     * Item specs used by the book:
     * {@code minecraft:iron_ingot}, {@code golemgarage:golem_fists@gold} (a part in a material),
     * {@code golemgarage:golem@diamond} (a matched golem), {@code golemgarage:cub#9} (a cub color),
     * and an optional {@code *count} on the end.
     */
    public static ItemStack stack(String spec) {
        int count = 1;
        int star = spec.indexOf('*');
        if (star > 0) {
            count = Integer.parseInt(spec.substring(star + 1));
            spec = spec.substring(0, star);
        }
        String material = null;
        int color = -1;
        int at = spec.indexOf('@');
        int hash = spec.indexOf('#');
        String id = spec;
        if (at > 0) {
            material = spec.substring(at + 1);
            id = spec.substring(0, at);
        } else if (hash > 0) {
            color = Integer.parseInt(spec.substring(hash + 1));
            id = spec.substring(0, hash);
        }
        Item item = BuiltInRegistries.ITEM.getOptional(ResourceLocation.parse(id)).orElse(Items.BARRIER);
        ItemStack stack;
        if (material != null && id.equals(GolemGarage.MOD_ID + ":golem")) {
            stack = GolemItem.stackFromTag(GolemData.preset(GolemMaterials.getOrIron(material),
                    "sentry_head", "plated_chest", "golem_fists", "stub_legs", "redstone_core"));
        } else {
            stack = new ItemStack(item, count);
            if (material != null) {
                stack.set(ModDataComponents.MATERIAL.get(), material);
            }
            if (color >= 0) {
                stack.set(ModDataComponents.COLOR.get(), color);
            }
        }
        stack.setCount(count);
        return stack;
    }
}
